#!/usr/bin/env python3
"""Create Open MPI hostfiles for the Pi cluster with a dedicated orchestrator.

The orchestrator (default pi119) only launches runs, collects and evaluates; it
never receives a rank. Workers are ordered by number, so hosts_k<N>.txt always
uses the same first N workers. One slot per worker by default.

    python tools/make_hostfiles.py cluster/hosts.txt --out cluster/hostfiles --sizes 3 4 8 16 118

Exit code 1 if a requested size needs more workers than available at the chosen
slots per host (the report names the missing hosts).
"""
import argparse
import json
import re
from pathlib import Path


def read_hosts(path: Path):
    hosts = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        fields = line.split("#", 1)[0].split()
        if fields:
            hosts[fields[0]] = fields[1] if len(fields) > 1 else None
    return hosts


def number(name: str):
    match = re.fullmatch(r"[A-Za-z]+(\d+)", name)
    return int(match.group(1)) if match else None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("hosts", type=Path, help="Host list: 'name [ip]' per line")
    ap.add_argument("--orchestrator", default="pi119")
    ap.add_argument("--exclude", nargs="*", default=[], help="Further hosts that must not receive ranks")
    ap.add_argument("--expected-range", nargs=2, type=int, default=(1, 120), metavar=("FIRST", "LAST"))
    ap.add_argument("--sizes", nargs="+", type=int, default=[3, 4, 8, 16, 118])
    ap.add_argument("--slots-per-host", type=int, default=1)
    ap.add_argument("--use-ip", action="store_true", help="Write IP addresses instead of host names")
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()
    hosts = read_hosts(args.hosts)
    if args.orchestrator not in hosts:
        raise SystemExit(f"Orchestrator {args.orchestrator} is not in {args.hosts}")
    excluded = {args.orchestrator, *args.exclude}
    workers = sorted((h for h in hosts if h not in excluded), key=lambda h: (number(h) is None, number(h), h))
    present = {number(h) for h in hosts}
    first, last = args.expected_range
    prefix = re.match(r"[A-Za-z]+", args.orchestrator).group(0)
    missing = [f"{prefix}{i}" for i in range(first, last + 1) if i not in present]
    args.out.mkdir(parents=True, exist_ok=True)
    report = {"orchestrator": args.orchestrator, "excluded": sorted(excluded), "workers": len(workers),
              "slots_per_host": args.slots_per_host, "missing_from_list": missing, "files": {}, "problems": []}
    for size in args.sizes:
        needed_hosts = -(-size // args.slots_per_host)
        if needed_hosts > len(workers):
            report["problems"].append(f"k={size} needs {needed_hosts} workers at {args.slots_per_host} slot(s), only {len(workers)} available")
            continue
        chosen = workers[:needed_hosts]
        lines = [f"# k={size}; orchestrator {args.orchestrator} excluded; generated by tools/make_hostfiles.py"]
        remaining = size
        for host in chosen:
            slots = min(args.slots_per_host, remaining)
            remaining -= slots
            lines.append(f"{hosts[host] if args.use_ip and hosts[host] else host} slots={slots}")
        path = args.out / f"hosts_k{size}.txt"
        path.write_text("\n".join(lines) + "\n", encoding="utf-8")
        report["files"][str(size)] = {"path": str(path), "first": chosen[0], "last": chosen[-1]}
    central = workers[0] if workers else None
    report["central_host"] = central
    (args.out / "hostfiles.json").write_text(json.dumps(report, indent=2), encoding="utf-8")
    print(json.dumps({k: v for k, v in report.items() if k != "files"}, indent=2))
    return 1 if report["problems"] else 0


if __name__ == "__main__":
    raise SystemExit(main())
